"""Normalize woodland cutouts and extend the existing Stage3 manifest."""
from pathlib import Path
from collections import Counter
from PIL import Image
import hashlib
import json
import importlib.util
import sys

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('sakura_art', ROOT/'tools/prepare-sakura-art-batch.py')
art = importlib.util.module_from_spec(spec)
spec.loader.exec_module(art)

def dump(path, data):
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2)+'\n', encoding='utf8')

def main():
    boss_vfx = '--boss-vfx' in sys.argv
    batch_path = ROOT/('docs/STAGE3_BOSS_VFX_20261116.json' if boss_vfx else 'docs/STAGE3_FOREST_20261116.json')
    batch = json.loads(batch_path.read_text(encoding='utf8'))
    records = []
    roles = {}
    previous = {a['path']: a for a in batch.get('assets', [])}
    for source in batch['sources']:
        src = ROOT/source['path']
        dest = ROOT/(f"assets/img/vfx/enemies/sakura-tengu/sakura-tengu__{source['id']}.webp" if boss_vfx
                     else f"assets/img/stages/sakura-pass/props/sakura-pass__{source['id']}.webp")
        record = previous.get(dest.relative_to(ROOT).as_posix())
        if not (record and dest.is_file() and art.sha(src) == record['source_sha256'] and art.sha(dest) == record['sha256']):
            with Image.open(src) as original:
                image, rect, crop = art.scene_image(original.convert('RGBA'), 768)
            art.save(image, dest)
            record = art.record(dest, src, id=source['id'], role=source['role'], category='boss_vfx' if boss_vfx else 'forest',
                                size=list(image.size), source_rect=rect, source_crop=list(crop), label=source['label'])
        records.append(record)
        roles[source['role']] = dict(path=record['path'], rect=record['source_rect'])
    manifest_path = ROOT/'assets/img/stages/sakura-pass/manifest.json'
    manifest = json.loads(manifest_path.read_text(encoding='utf8'))
    selected = {(a['path'], a['sha256']) for a in manifest['assets'] if a.get('status') == 'USER_SELECTED_RUNTIME'}
    for record in records:
        if (record['path'], record['sha256']) in selected:
            record['status'] = 'USER_SELECTED_RUNTIME'
    manifest['assets'] = [a for a in manifest['assets'] if a['role'] not in roles]+records
    manifest['boss_vfx_batch' if boss_vfx else 'forest_batch'] = batch_path.relative_to(ROOT).as_posix()
    dump(manifest_path, manifest)
    data_path = ROOT/'js/sakura-art-data.js'
    data = json.loads(data_path.read_text(encoding='utf8').split('Object.freeze(', 1)[1].rsplit(');', 1)[0])
    data['bossVfx' if boss_vfx else 'forest'] = roles
    data_path.write_text('// GENERATED by Stage3 art tools from the runtime art manifest.\nwindow.SAKURA_ART_DATA = Object.freeze('
                        +json.dumps(data, ensure_ascii=False, separators=(',', ':'))+');\n', encoding='utf8')
    inventory_path = ROOT/'docs/ASSET_INVENTORY.json'
    inventory = json.loads(inventory_path.read_text(encoding='utf8'))
    by_path = {a['path']: a for a in inventory['files']}
    for record in records:
        path = ROOT/record['path']
        old_record = by_path.get(record['path'], {})
        sha256 = hashlib.sha256(path.read_bytes()).hexdigest()
        status = old_record.get('status', 'trial_pending_review') if old_record.get('sha256') == sha256 else 'trial_pending_review'
        by_path[record['path']] = dict(path=record['path'], status=status, bytes=path.stat().st_size, sha256=sha256)
    inventory['files'] = list(by_path.values())
    inventory['totals'] = dict(files=len(by_path), by_status=dict(Counter(a['status'] for a in by_path.values())))
    dump(inventory_path, inventory)
    batch['status'] = 'ART_CANDIDATE_USER_REVIEW_PENDING'
    batch['assets'] = records
    dump(batch_path, batch)
    print(f"Imported {len(records)} transparent {'boss VFX' if boss_vfx else 'forest'} images; unchanged previous images retained.")

if __name__ == '__main__':
    main()
