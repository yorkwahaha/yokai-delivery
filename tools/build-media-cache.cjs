// Rebuild before publishing changes to image or audio files. No media is precached.
const fs = require('node:fs');
const pathUtil = require('node:path');
const { createHash } = require('node:crypto');
const { execFileSync } = require('node:child_process');
const tracked = new Set(execFileSync('git',['ls-files','--cached','--','assets/img','assets/audio'],{encoding:'utf8'}).trim().split(/\r?\n/));
// Walk the actual web assets, including new, not-yet-tracked VFX WebPs and MP3s.
const files=[];
function collect(dir){
  for(const entry of fs.readdirSync(dir,{withFileTypes:true})){
    const filename=pathUtil.join(dir,entry.name);
    if(entry.isDirectory())collect(filename);
    else if(/\.(webp|png|jpe?g|svg|mp3)$/i.test(filename)) {
      const url=filename.replace(/\\/g,'/');
      // Untracked source PNG drafts are not shipped. New optimized WebP/MP3s are.
      if(tracked.has(url)||/\.(webp|mp3)$/i.test(url))files.push(url);
    }
  }
}
collect('assets/img');collect('assets/audio');
const revisions = Object.fromEntries([...new Set(files)].filter(path => /\.(webp|png|jpe?g|svg|mp3)$/.test(path)).sort().map(path =>
  [path, createHash('sha256').update(fs.readFileSync(path)).digest('hex').slice(0,24)]));
fs.writeFileSync('service-worker.js', '// Generated by tools/build-media-cache.cjs; cache media only, never HTML or scripts.\nconst MEDIA_REVISIONS = ' + JSON.stringify(revisions, null, 2) + ';\n' + fs.readFileSync('tools/media-cache-worker.js','utf8'));
console.log(`Generated content revisions for ${Object.keys(revisions).length} media files.`);
