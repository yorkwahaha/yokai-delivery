// Rebuild before publishing changes to image or audio files. No media is precached.
const fs = require('node:fs');
const { execFileSync } = require('node:child_process');
const { createHash } = require('node:crypto');
const files = execFileSync('git', ['ls-files', '--', 'assets/img', 'assets/audio']).toString().trim().split(/\r?\n/);
for (const key of ['hud_lantern_oil','hud_radar_frame','hud_omamori_hint_listen','hud_skill_fan']) files.push(`assets/img/ui/${key}.webp`);
// New pictorial awakening seal also needs a content revision before its first Git add/commit.
files.push('assets/img/ui/awaken_seal.svg');
const revisions = Object.fromEntries([...new Set(files)].filter(path => /\.(webp|png|jpe?g|svg|mp3)$/.test(path)).sort().map(path =>
  [path, createHash('sha256').update(fs.readFileSync(path)).digest('hex').slice(0,24)]));
fs.writeFileSync('service-worker.js', '// Generated by tools/build-media-cache.cjs; cache media only, never HTML or scripts.\nconst MEDIA_REVISIONS = ' + JSON.stringify(revisions, null, 2) + ';\n' + fs.readFileSync('tools/media-cache-worker.js','utf8'));
console.log(`Generated content revisions for ${Object.keys(revisions).length} media files.`);
