'use strict';
// Focused balance contracts. These are formula checks, not automated playtests.
const test = require('node:test');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const CFG = require('../js/config.js');
const { loadGame } = require('./helpers/game-runtime.cjs');

const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync('js/game-attack-specs.js', 'utf8'), ctx,
  { filename: 'js/game-attack-specs.js' });
const resolve = ctx.window.GAME_ATTACK_SPECS.resolveAttackSpec;
function spec(skillId, level, mutations = [], rate = 0) {
  return resolve(skillId, level, { mutations, duos: [], passives: { crit: 0 } }, {}, {
    WL: {}, W: 900, b: { crit: 0 }, buildMutations: [], buildDuos: [],
    getEffectiveRate: () => rate, getEffectiveDmg: () => 1,
    getEffectiveReachMultiplier: () => 1
  });
}
const close = (value, expected) => assert.ok(Math.abs(value - expected) < 1e-8,
  `expected ${expected}, got ${value}`);

test('Nov14: Iai charge gains 24% damage for exactly 0.08s extra cooldown', () => {
  for (const rate of [0, 1, 4]) {
    for (const level of [1, 3, 5]) {
      const base = spec('katana', level, [], rate);
      const charge = spec('katana', level, ['mut_iaicharge'], rate);
      close(charge.cooldown - base.cooldown, 0.08);
      close(charge.slashDmg / base.slashDmg, 1.24);
      close(charge.windDmg / base.windDmg, 1.24);
    }
  }
});

test('Nov14: Ofuda Lv5 raises direct damage only; splash and lower levels stay intact', () => {
  for (const level of [1, 2, 3, 4]) {
    const s = spec('boom', level);
    close(s.damage, 1.5 + level * .7);
    close(s.splashDamage, s.damage * .2);
  }
  const base = spec('boom', 5);
  const fan = spec('boom', 5, ['mut_boom_fan']);
  const split = spec('boom', 5, ['mut_splitblast']);
  close(base.damage, 8);
  close(base.splashDamage, 5);
  close(fan.damage, 4.8);
  close(fan.splashDamage, 3);
  close(split.splitblastDirectDamage, 2);
  close(split.splitblastSplashDamage, 1.25);
});

test('Nov14: rain-port XP costs no longer stack discounted requirements with 3-XP gems', () => {
  const s1 = CFG.resolveMobDifficultyProfile({ id: 'night-town', pacing: {} });
  const s2 = CFG.resolveMobDifficultyProfile({ id: 'rain-port', pacing: {} });
  const hard = CFG.resolveMobDifficultyProfile({ id: 'rain-port', pacing: { mobDifficulty: 'hard' } });
  close(s1.xpNeedScale, .9);
  close(s2.xpNeedScale, 1.05);
  close(hard.xpNeedScale, 1);
  const first = loadGame({ seed: 11, stage: 'night-town' });
  first.start('night-town');
  const second = loadGame({ seed: 11, stage: 'rain-port' });
  second.start('rain-port');
  assert.equal(first.snapshot().xpNeed, Math.round(CFG.xpNeed(1) * .9));
  assert.equal(second.snapshot().xpNeed, Math.round(CFG.xpNeed(1) * 1.05));
  // Audit sample: 1204 ordinary mobs generated by t=480; assume 6 completed
  // orders and 55/75/90% gem pickup. This is a calibration, not live gameplay.
  const estimate = pickup => {
    let xp = 1204 * pickup * 3 + 6 * CFG.DELIVERY_XP, level = 1;
    while (xp >= Math.round(CFG.xpNeed(level) * s2.xpNeedScale)) {
      xp -= Math.round(CFG.xpNeed(level) * s2.xpNeedScale);
      level++;
    }
    return level;
  };
  assert.deepEqual([.55, .75, .9].map(estimate), [25, 29, 31]);
});
